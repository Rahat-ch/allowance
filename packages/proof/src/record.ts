/**
 * The testnet proof: what the run recorded (docs/proof/testnet.json) and the document a
 * judge reads (docs/proof/testnet.md), rendered from it. A test checks the two match.
 */

export type ProofTx = { label: string; hash: string };

export type ProofStep = {
  title: string;
  /** What the run asserted, in words. */
  checks: string[];
  request_id: string;
  outcome: string;
  status: string;
  blocked_reason?: string | null;
  transactions: ProofTx[];
};

export type Proof = {
  network: "testnet";
  ran_at: string;
  allowance: string;
  payer_account: string;
  owner: string;
  payee: string;
  facilitator_relayer: string;
  signer: string;
  usdc: string;
  policy: { daily_cap_usd: string; auto_limit_usd: string; hard_ceiling_usd: string; velocity_limit: number };
  deploy: ProofTx[];
  steps: ProofStep[];
};

const EXPLORER = "https://testnet.nearblocks.io";

export const txLink = (hash: string) => `${EXPLORER}/txns/${hash}`;
export const accountLink = (id: string) => `${EXPLORER}/address/${id}`;

const HASH = /^[1-9A-HJ-NP-Za-km-z]{43,44}$/;

/** Shape checks a recorded proof must pass before it's rendered or trusted. */
export function validateProof(p: Proof): string[] {
  const problems: string[] = [];
  const all = [...p.deploy, ...p.steps.flatMap((s) => s.transactions)];
  for (const t of all) if (!HASH.test(t.hash)) problems.push(`not a transaction hash: ${t.label} ${t.hash}`);
  const outcomes = p.steps.map((s) => `${s.outcome}/${s.status}`);
  for (const want of ["Approved/Signed", "Blocked/Blocked", "Pending/Signed"]) {
    if (!outcomes.includes(want)) problems.push(`no ${want} step`);
  }
  return problems;
}

export function renderProof(p: Proof): string {
  const link = (t: ProofTx) => `- ${t.label}: [${t.hash}](${txLink(t.hash)})`;
  const lines = [
    "# Testnet proof run",
    "",
    "Generated by `pnpm --filter proof run testnet` from `docs/proof/testnet.json`; a test checks this file matches it.",
    "",
    `Run at ${p.ran_at} on NEAR testnet with real infrastructure:`,
    "",
    `- **Allowance** (locked: no full-access key): [${p.allowance}](${accountLink(p.allowance)})`,
    `- **Payer Account** (only keys derived through Chain Signatures): [${p.payer_account}](${accountLink(p.payer_account)})`,
    `- **Owner**: [${p.owner}](${accountLink(p.owner)}); **Payee** (the demo seller): [${p.payee}](${accountLink(p.payee)})`,
    `- **Signer**: \`${p.signer}\` (NEAR Chain Signatures MPC)`,
    `- **USDC**: Circle testnet USDC \`${p.usdc}\``,
    `- **Facilitator**: the official \`@x402/near\` exact facilitator, unmodified, self-hosted in process; relayer [${p.facilitator_relayer}](${accountLink(p.facilitator_relayer)})`,
    `- **Policy**: Daily Cap $${p.policy.daily_cap_usd}, Auto Limit $${p.policy.auto_limit_usd}, Hard Ceiling $${p.policy.hard_ceiling_usd}, Velocity Limit ${p.policy.velocity_limit}/hour`,
    "",
    "The Agent used only its function-call key (`request_spend`), through the Allowance MCP server's tools.",
    "",
    "## Deploy",
    "",
    ...p.deploy.map(link),
  ];
  for (const s of p.steps) {
    lines.push(
      "",
      `## ${s.title}`,
      "",
      `Request ID \`${s.request_id}\`: Outcome **${s.outcome}**, status **${s.status}**${s.blocked_reason ? `, reason **${s.blocked_reason}**` : ""}.`,
      "",
      ...s.checks.map((c) => `- ✓ ${c}`),
      "",
      ...s.transactions.map(link),
    );
  }
  return lines.join("\n") + "\n";
}
